/**
 * The dictionary *shape* with string leaves. Widening matters: `typeof en`
 * alone would make every leaf a literal type and no translation could ever
 * satisfy it. With Widen, id.ts must have exactly the same keys but is free to
 * carry different text.
 */
type Widen<T> = T extends string ? string : { readonly [K in keyof T]: Widen<T[K]> };
export type Dictionary = Widen<typeof en>;
